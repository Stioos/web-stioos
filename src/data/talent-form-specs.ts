export function getTalentFormSpec(rawSlug: string): OptionFormSpec {
  const optionSlug = rawSlug.replace(/\//g, "-");
  if (TALENT_FORM_SPECS[rawSlug]) {
    return TALENT_FORM_SPECS[rawSlug];
  }
  if (TALENT_FORM_SPECS[optionSlug]) {
    return TALENT_FORM_SPECS[optionSlug];
  }

  // Strip known category/service prefixes if slug is nested (e.g. "train-to-hire-custom-cohort-curriculum")
  const stripped = optionSlug.replace(
    /^(talent-solutions-|train-to-hire-|hire-to-train-|corporate-training-|talent-recruitment-|talent-deployment-|workforce-solutions-|get-trained-|get-placed-|get-certified-|joining-terms-|learning-terms-)/,
    ""
  );
  if (TALENT_FORM_SPECS[stripped]) {
    return TALENT_FORM_SPECS[stripped];
  }

  // Exact matching for custom cohort curriculum
  if (optionSlug.includes("custom-cohort-curriculum")) {
    return (
      TALENT_FORM_SPECS["custom-cohort-curriculum"] ||
      TALENT_FORM_SPECS["train-to-hire-custom-cohort-curriculum"]
    );
  }

  // Exact matching for AI Candidate Screening
  if (optionSlug.includes("ai-candidate-screening") || optionSlug.includes("ai-screening")) {
    return TALENT_FORM_SPECS["ai-candidate-screening"];
  }

  // Exact matching for Training Sprint Delivery
  if (
    optionSlug.includes("training-sprint-delivery") ||
    optionSlug.includes("training-sprints") ||
    optionSlug.includes("training-sprint")
  ) {
    return TALENT_FORM_SPECS["training-sprint-delivery"];
  }

  // Exact matching for main Get Trained group
  if (optionSlug === "get-trained") {
    return TALENT_FORM_SPECS["get-trained"];
  }

  // Check sub-slug matches for joining terms and learning terms
  if (optionSlug.includes("joining-terms")) {
    if (optionSlug.includes("curriculum")) return TALENT_FORM_SPECS["joining-terms-curriculum"];
    if (optionSlug.includes("pricing")) return TALENT_FORM_SPECS["joining-terms-pricing"];
    if (optionSlug.includes("agreement")) return TALENT_FORM_SPECS["joining-terms-agreement"];
    return TALENT_FORM_SPECS["joining-terms"];
  }

  if (optionSlug.includes("learning-terms")) {
    if (optionSlug.includes("self-learning")) return TALENT_FORM_SPECS["learning-terms-self-learning"];
    if (optionSlug.includes("projects")) return TALENT_FORM_SPECS["learning-terms-projects-development"];
    if (optionSlug.includes("curriculum")) return TALENT_FORM_SPECS["joining-terms-curriculum"];
    return TALENT_FORM_SPECS["learning-terms"];
  }

  // Fallback default spec if an unknown slug is provided
  return {
    optionSlug,
    optionTitle: optionSlug.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
    groupSlug: "talent-solutions",
    groupName: "Talent Solutions",
    side: "candidate",
    icon: Briefcase,
    apply: {
      kicker: "Candidate Application",
      title: `Apply for ${optionSlug.replace(/-/g, " ")}`,
      blurb: "Submit your details for personalized enrollment and role matching.",
      badge: "Verified Candidate Pathway",
      trackLabel: "Technical Track",
      tracks: ["Software Engineering", "AI & Machine Learning", "Cloud & DevOps", "Full-Stack Development"],
      statementPlaceholder: "Describe your background and goals...",
    },
    getStarted: {
      kicker: "Enterprise Engagement",
      title: `Get Started with ${optionSlug.replace(/-/g, " ")}`,
      blurb: "Tailored engagement models with guaranteed SLAs and pre-screened talent.",
      badge: "48h Shortlists · Verified SLA",
      scopeLabel: "Capacity Required",
      scopeOptions: ["1–3 Engineers", "4–10 Engineers", "Dedicated Pod", "Enterprise Division"],
      stackLabel: "Required Stack",
      stackOptions: ["React / Node", "Python / AI", "Cloud Native", "Java Enterprise"],
      notesPlaceholder: "Detail your requirements...",
    },
    consultation: {
      kicker: "Technical Consultation",
      title: `Schedule Discovery Call for ${optionSlug.replace(/-/g, " ")}`,
      blurb: "30-minute consultation with a senior practice director.",
      badge: "30-Min Strategy Call",
      focusLabel: "Consultation Focus",
      focusOptions: ["Requirements Scoping", "Pricing & SLAs", "Custom Technical Review"],
      attendeeLabel: "Your Role",
      attendeeOptions: ["Engineering Leader", "Talent Acquisition", "Candidate / Learner"],
      notesPlaceholder: "What would you like to discuss?",
    },
  };
}
